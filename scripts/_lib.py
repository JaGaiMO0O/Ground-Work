REQUIRED_CARD_SECTIONS = ["Owns", "Interfaces", "Landmines", "Do not read"]
REQUIRED_CARD_FIELDS = ["Surveyed:", "Confidence:", "Stack:", "Health:"]
# Exactly one of these locates the area. Which one depends on its kind.
CARD_SOURCE_FIELDS = ["Path:", "Repo:", "Schema:", "Location:"]

GENERATED_HEADER = "GENERATED"
