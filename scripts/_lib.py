def rgignore_text(project: Project) -> str:
    """Render .rgignore from project.yaml. The single canonical generator -
    sync.py writes it, check.py compares against it."""
    lines = [
        f"# {GENERATED_HEADER} by scripts/sync.py from project.yaml.",
        "# Do not hand-edit. Re-run: python scripts/sync.py",
        "",
        "# --- always ---",
        ".git/",
        "systems/**/.git/",
        "__pycache__/",
        "",
        "# --- credential-bearing files ---",
        "# These also strip noisy config out of every search result.",
    ]
    lines += SECRET_FILE_PATTERNS
    for area in project.areas:
        if not area.exclude_from_search:
            continue
        lines += ["", f"# --- {area.name} ---"]
        for pattern in area.exclude_from_search:
            lines.append(f"{area.search_root}{str(pattern).lstrip('/')}")
    return "\n".join(lines) + "\n"


