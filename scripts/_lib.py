def profile_dir(project: Project) -> "Path | None":
    candidate = PROFILES_DIR / project.profile
    return candidate if candidate.is_dir() else None


def load_profile_rules(project: Project):
    """Import profiles/<profile>/rules.py, or None. Never raises."""
    directory = profile_dir(project)
    if directory is None:
        return None
    module_path = directory / "rules.py"
    if not module_path.is_file():
        return None
    import importlib.util

    spec = importlib.util.spec_from_file_location(
        f"profile_{project.profile}_rules", module_path
    )
    if spec is None or spec.loader is None:
        return None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


