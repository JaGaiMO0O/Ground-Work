PROFILES_DIR = ROOT / "profiles"

ADAPTER_FAMILIES = ("db", "capture", "test")
VALID_KINDS = ("local", "repo", "database", "fileshare")
VALID_ACCESS = ("read-only", "write")

# A ref that moves under you. A card describes a commit; if the ref drifts, the
# card silently becomes fiction.
MOVING_REFS = {"main", "master", "develop", "trunk", "default", "HEAD"}

