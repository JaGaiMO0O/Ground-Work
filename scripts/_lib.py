def resolve_adapter(area: Area, family: str):
    """-> (name, path).

    name is None  -> family not declared for this area (not applicable)
    path is None  -> declared but no such adapter on disk (an error)
    """
    name = (area.adapters or {}).get(family)
    if not name or str(name).lower() == "none":
        return None, None
    for base in adapter_search_paths(family):
        for ext in (".sh", ".py", ".ps1", ".cmd", ""):
            candidate = base / f"{name}{ext}"
            if candidate.is_file():
                return str(name), candidate
    return str(name), None


def adapter_search_paths(family: str) -> "list[Path]":
    """Core first, then every profile. Profiles ship their own adapters."""
    found = [SCRIPTS_DIR / "adapters" / family]
    if PROFILES_DIR.is_dir():
        for profile in sorted(PROFILES_DIR.iterdir()):
            candidate = profile / "adapters" / family
            if candidate.is_dir():
                found.append(candidate)
    return found


def adapter_command(path: Path) -> "list[str]":
    """Argv prefix for invoking an adapter, chosen by extension."""
    suffix = path.suffix.lower()
    if suffix == ".py":
        return [sys.executable, str(path)]
    if suffix == ".ps1":
        return ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                "-File", str(path)]
    if suffix == ".sh":
        return ["bash", str(path)]
    return [str(path)]


def load_dotenv(path: "Path | None" = None) -> dict:
    """Read .env into a dict for the CHILD process environment.

    This is the only place .env is read. Values are never printed, logged, or
    returned on stdout - that is the entire reason credentials travel this way
    instead of on a command line where they would land in a transcript.
    """
    path = path or (ROOT / ".env")
    env: dict = {}
    if not path.exists():
        return env
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        env[key.strip()] = value
    return env


def adapter_env(area: Area) -> dict:
    """The variables every adapter receives. Documented in docs/adapters.md -
    an adapter never has to parse project.yaml."""
    return {
        "PROJECT_ROOT": str(ROOT),
        "AREA_NAME": area.name,
        "AREA_KIND": area.kind,
        "AREA_REF": area.ref or "",
        "AREA_CHECKOUT": str(area.checkout),
        "AREA_CARD_DIR": str(area.card_dir),
        "AREA_SCHEMA_OWNERS": ",".join(str(o) for o in area.schema_owners),
        "AREA_DATABASE": str((area.stack or {}).get("database", "")),
    }


def run_adapter(
    area: Area,
    family: str,
    verb: str,
    extra: "tuple | list" = (),
    out: "Path | None" = None,
) -> int:
    """Resolve and exec the adapter. Returns its exit code verbatim.

    Exit 3 ('not applicable') is a normal answer, not a failure: an area with no
    observable boundary genuinely has no 'record' verb.
    """
    name, path = resolve_adapter(area, family)
    if name is None:
        info(f"     {area.name}: no '{family}' adapter declared - nothing to do")
        return 3
    if path is None:
        err(f"{area.name}: adapter {name!r} for '{family}' not found")
        info("       Looked in: " + ", ".join(
            str(p.relative_to(ROOT)) for p in adapter_search_paths(family)))
        info("       See docs/adapters.md")
        return 1

    argv = adapter_command(path) + [verb, "--area", area.name]
    if out is not None:
        Path(out).parent.mkdir(parents=True, exist_ok=True)
        argv += ["--out", str(out)]
    argv += [str(a) for a in extra]

    child = {**os.environ, **load_dotenv(), **adapter_env(area)}
    code = subprocess.run(argv, cwd=str(ROOT), env=child).returncode

    if code == 0:
        ok(f"{area.name}: {family} {verb} -> {out or 'stdout'}")
    elif code == 3:
        info(f"     {area.name}: {family} {verb} not applicable ({name})")
    elif code == 4:
        err(f"{area.name}: {name} is missing credentials or configuration")
        info("       Fill the relevant entries in .env - see .env.example")
    elif code == 5:
        err(f"{area.name}: {name} could not reach the upstream system")
    else:
        err(f"{area.name}: {name} {verb} failed (exit {code})")
    return code


def adapter_status(code: int) -> int:
    """Collapse an adapter exit code into a process exit status.
    'Not applicable' is not a failure."""
    return 0 if code in (0, 3) else 1


