def git(*args: str, cwd: "Path | None" = None, check: bool = False):
    return subprocess.run(
        ["git", *args],
        cwd=str(cwd or ROOT),
        capture_output=True,
        text=True,
        check=check,
    )


def is_git_repo(cwd: "Path | None" = None) -> bool:
    result = git("rev-parse", "--is-inside-work-tree", cwd=cwd)
    return result.returncode == 0 and result.stdout.strip() == "true"


def tracked_files() -> "list[str]":
    result = git("ls-files")
    return result.stdout.splitlines() if result.returncode == 0 else []


def has_commits() -> bool:
    """A freshly `git init`ed repo tracks nothing, which would make every
    'is X tracked?' check fire spuriously on day one."""
    return git("rev-parse", "--verify", "HEAD").returncode == 0


def is_pinned(ref: "str | None") -> bool:
    """A ref is pinned if it is a SHA or a tag-shaped name, not a branch."""
    if not ref:
        return False
    if ref in MOVING_REFS:
        return False
    if re.fullmatch(r"[0-9a-f]{7,40}", ref):
        return True
    return not ref.startswith(("refs/heads/", "heads/"))


def which(tool: str) -> "str | None":
    from shutil import which as _which

    return _which(tool)
