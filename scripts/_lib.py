def load_yaml(path: Path):
    """-> (data, parser_name). Falls back to the bundled subset parser."""
    text = Path(path).read_text(encoding="utf-8")
    try:
        import yaml  # type: ignore
    except ImportError:
        import _minyaml

        try:
            return _minyaml.parse(text) or {}, "minyaml"
        except _minyaml.MinYamlError as exc:
            die(
                f"{path.name}: {exc}\n"
                "     The bundled fallback parser handles only the documented "
                "subset.\n     Fix the file, or install PyYAML: pip install pyyaml"
            )
    return yaml.safe_load(text) or {}, "pyyaml"


