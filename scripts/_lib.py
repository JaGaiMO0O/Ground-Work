"""Shared helpers for the control-plane scripts.

Control plane ONLY: git orchestration, YAML, paths, validation, reporting.
Nothing here knows how to build or run your project. Anything that has to touch
a live external system goes through an adapter - see docs/adapters.md.

The model is one collection: AREAS. An area is a named part of the work with a
card describing it. Its `kind` says where it physically lives:

    local      part of this repository, described by `paths:`   (the default)
    repo       an external repository, checked out into systems/
    database   logic that lives in a database, with no repo at all
    fileshare  anything else with no repo

A general project declares local areas. A legacy-modernization project declares
repo and database areas. Same model, same cards, same validation.
"""

