@dataclass
class Area:
    name: str
    kind: str = "local"
    survey: bool = False
    owner: str = ""
    access: str = "read-only"

    # local
    paths: list = field(default_factory=list)

    # repo
    url: "str | None" = None
    ref: "str | None" = None
    sparse: list = field(default_factory=list)
    derive: list = field(default_factory=list)

    # database
    schema_owners: list = field(default_factory=list)

    exclude_from_search: list = field(default_factory=list)
    stack: dict = field(default_factory=dict)
    adapters: dict = field(default_factory=dict)

    @property
    def checkout(self) -> Path:
        """Where a repo area lands on disk. Meaningless for other kinds."""
        return ROOT / "systems" / self.name

    @property
    def card_dir(self) -> Path:
        return MAP_DIR / self.name

    @property
    def card(self) -> Path:
        return self.card_dir / "CARD.md"

    @property
    def clonable(self) -> bool:
        return self.kind == "repo"

    @property
    def search_root(self) -> str:
        """Path prefix for this area's exclusions, relative to the repo root."""
        return f"systems/{self.name}/" if self.kind == "repo" else ""

    def owns_path(self, rel_path: str) -> bool:
        """Does `rel_path` (repo-relative, posix) belong to this area?"""
        from fnmatch import fnmatch

        rel_path = rel_path.replace("\\", "/").lstrip("./")
        if self.kind == "repo":
            return rel_path.startswith(f"systems/{self.name}/")
        for pattern in self.paths:
            pattern = str(pattern).replace("\\", "/")
            if fnmatch(rel_path, pattern) or rel_path.startswith(
                pattern.split("*", 1)[0].rstrip("/") + "/"
            ):
                return True
        return False


@dataclass
class Project:
    name: str
    profile: str
    areas: "list[Area]"
    commands: dict
    parser: str
    path: Path
    errors: "list[str]" = field(default_factory=list)

    def get(self, name: str) -> "Area | None":
        for a in self.areas:
            if a.name == name:
                return a
        return None

    def require(self, name: str) -> Area:
        found = self.get(name)
        if found is None:
            known = ", ".join(a.name for a in self.areas) or "(none declared)"
            die(f"unknown area {name!r}. Declared: {known}")
        return found  # type: ignore[return-value]

    def area_for(self, rel_path: str) -> "Area | None":
        for a in self.areas:
            if a.owns_path(rel_path):
                return a
        return None

    @property
    def repo_areas(self) -> "list[Area]":
        return [a for a in self.areas if a.kind == "repo"]


def _as_list(value) -> list:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def load_project(path: Path = PROJECT_FILE) -> Project:
    """Load and normalize project.yaml.

    Schema problems are collected into `.errors` rather than raised, so check.py
    reports all of them in one pass instead of one per run.
    """
    if not path.exists():
        die(
            f"{path.name} not found. Are you in the project root?\n"
            "     If this is a new project: python scripts/init.py"
        )

    data, parser = load_yaml(path)
    errors: list[str] = []

    if not isinstance(data, dict):
        die(f"{path.name}: expected a mapping at the top level")

    defaults = data.get("defaults") or {}
    name = str(data.get("project") or "<unnamed>")
    profile = str(data.get("profile") or "general")
    commands = data.get("commands") or {}
    if not isinstance(commands, dict):
        errors.append("'commands' must be a mapping of name -> shell command")
        commands = {}

    if profile and not (PROFILES_DIR / profile).is_dir():
        errors.append(
            f"profile {profile!r} has no directory under profiles/. "
            f"Available: {', '.join(sorted(p.name for p in PROFILES_DIR.iterdir() if p.is_dir())) if PROFILES_DIR.is_dir() else 'none'}"
        )

    areas: list[Area] = []
    seen: set[str] = set()

    for idx, raw in enumerate(_as_list(data.get("areas"))):
        where = f"areas[{idx}]"
        if not isinstance(raw, dict):
            errors.append(f"{where}: expected a mapping")
            continue

        aname = raw.get("name")
        if not aname:
            errors.append(f"{where}: missing required field 'name'")
            continue
        aname = str(aname)
        if aname in seen:
            errors.append(f"{where}: duplicate area name {aname!r}")
            continue
        seen.add(aname)

        kind = str(raw.get("kind", "local"))
        if kind not in VALID_KINDS:
            errors.append(f"{aname}: kind {kind!r} not one of {VALID_KINDS}")

        access = str(raw.get("access", defaults.get("access", "read-only")))
        if access not in VALID_ACCESS:
            errors.append(f"{aname}: access {access!r} not one of {VALID_ACCESS}")

        paths = _as_list(raw.get("paths"))
        url, ref = raw.get("url"), raw.get("ref")

        if kind == "local":
            if not paths:
                errors.append(
                    f"{aname}: kind 'local' requires 'paths' - without it nothing "
                    "can tell which files belong to this area"
                )
            if url or ref:
                errors.append(f"{aname}: kind 'local' has no 'url'/'ref'")
        elif kind == "repo":
            if not url:
                errors.append(f"{aname}: kind 'repo' requires 'url'")
            if not ref:
                errors.append(
                    f"{aname}: kind 'repo' requires 'ref' - an unpinned area "
                    "cannot be surveyed reliably"
                )
        elif url or ref:
            errors.append(
                f"{aname}: kind {kind!r} has no repo, so 'url'/'ref' are meaningless"
            )

        adapters = raw.get("adapters") or {}
        if not isinstance(adapters, dict):
            errors.append(f"{aname}: 'adapters' must be a mapping")
            adapters = {}
        for fam in adapters:
            if fam not in ADAPTER_FAMILIES:
                errors.append(
                    f"{aname}: unknown adapter family {fam!r}; "
                    f"expected one of {ADAPTER_FAMILIES}"
                )

        for d_idx, d in enumerate(_as_list(raw.get("derive"))):
            if not isinstance(d, dict) or not {"tool", "from", "to"} <= set(d):
                errors.append(f"{aname}: derive[{d_idx}] needs 'tool', 'from' and 'to'")

        areas.append(
            Area(
                name=aname,
                kind=kind,
                survey=bool(raw.get("survey", defaults.get("survey", False))),
                owner=str(raw.get("owner") or ""),
                access=access,
                paths=paths,
                url=str(url) if url else None,
                ref=str(ref) if ref else None,
                sparse=_as_list(raw.get("sparse")),
                derive=_as_list(raw.get("derive")),
                schema_owners=_as_list(raw.get("schema_owners")),
                exclude_from_search=_as_list(raw.get("exclude_from_search")),
                stack=raw.get("stack") or {},
                adapters=adapters,
            )
        )

    return Project(
        name=name,
        profile=profile,
        areas=areas,
        commands=commands,
        parser=parser,
        path=path,
        errors=errors,
    )


