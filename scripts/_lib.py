_COLOR = sys.stderr.isatty() and not os.environ.get("NO_COLOR")

# Our own strings are ASCII by policy, but filenames and other external data are
# not. A cp1252 console raises UnicodeEncodeError rather than degrading, which
# would crash a reporting tool over a character in somebody's path.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(errors="replace")
    except (AttributeError, ValueError):  # not a reconfigurable stream
        pass


def _c(code: str, text: str) -> str:
    return f"\033[{code}m{text}\033[0m" if _COLOR else text


def info(msg: str) -> None:
    print(msg, file=sys.stderr)


def ok(msg: str) -> None:
    print(f"{_c('32', 'ok')}   {msg}", file=sys.stderr)


def warn(msg: str) -> None:
    print(f"{_c('33', 'warn')} {msg}", file=sys.stderr)


def err(msg: str) -> None:
    print(f"{_c('31', 'FAIL')} {msg}", file=sys.stderr)


def die(msg: str, code: int = 1):
    err(msg)
    raise SystemExit(code)


def estimate_tokens(text: str) -> int:
    """Rough token count. ~4 chars/token is close enough for budgeting."""
    return max(1, round(len(text) / 4))


